/**
 * Метод Object.defineProperty() определяет новое или изменяет существующее свойство объекта
 * 
 * Синтаксис:
 * Object.defineProperty(obj, prop, descriptor)
 * 
 * Параметры:
 * obj - объект, в котором определяется свойство
 * prop - имя определяемого или изменяемого свойства
 * descriptor - дескриптор определяемого или изменяемого свойства
 * 
 * Возвращаемое значение:
 * Объект, которому был передан метод
 */

// Пример 1: Определение простого свойства
const person = {};
Object.defineProperty(person, 'name', {
    value: 'Иван',
    writable: true,
    enumerable: true,
    configurable: true
});
console.log(person.name); // 'Иван'

// Пример 2: Создание свойства только для чтения
const config = {};
Object.defineProperty(config, 'apiKey', {
    value: 'secret123',
    writable: false,
    enumerable: true,
    configurable: false
});

// config.apiKey = 'newKey'; // TypeError: Cannot assign to read only property 'apiKey'

// Пример 3: Создание свойства с геттером и сеттером
const user = {};
Object.defineProperty(user, 'fullName', {
    get() {
        return `${this.firstName} ${this.lastName}`;
    },
    set(value) {
        [this.firstName, this.lastName] = value.split(' ');
    },
    enumerable: true,
    configurable: true
});

user.firstName = 'Иван';
user.lastName = 'Петров';
console.log(user.fullName); // 'Иван Петров'

// Пример 4: Создание вычисляемого свойства
const circle = {};
Object.defineProperty(circle, 'radius', {
    value: 5,
    writable: true
});

Object.defineProperty(circle, 'area', {
    get() {
        return Math.PI * this.radius * this.radius;
    },
    enumerable: true
});

console.log(circle.area); // 78.53981633974483

// Пример 5: Создание свойства с валидацией
const product = {};
Object.defineProperty(product, 'price', {
    get() {
        return this._price;
    },
    set(value) {
        if (value < 0) {
            throw new Error('Цена не может быть отрицательной');
        }
        this._price = value;
    },
    enumerable: true
});

product.price = 100;
console.log(product.price); // 100
