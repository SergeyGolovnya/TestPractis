/**
 * Метод Object.keys() возвращает массив имен перечисляемых свойств объекта
 * 
 * Синтаксис:
 * Object.keys(obj)
 * 
 * Параметры:
 * obj - объект, чьи перечисляемые свойства будут возвращены
 * 
 * Возвращаемое значение:
 * Массив строк, представляющих имена перечисляемых свойств объекта
 */

// Пример 1: Получение ключей простого объекта
const person = {
    name: 'Иван',
    age: 30,
    city: 'Москва'
};
const keys = Object.keys(person);
console.log(keys); // ['name', 'age', 'city']

// Пример 2: Подсчет количества свойств
const count = Object.keys(person).length;
console.log(count); // 3

// Пример 3: Использование с массивом объектов
const users = [
    { id: 1, name: 'Анна' },
    { id: 2, name: 'Петр' }
];
const firstUserKeys = Object.keys(users[0]);
console.log(firstUserKeys); // ['id', 'name']

// Пример 4: Проверка наличия свойств
const hasName = Object.keys(person).includes('name');
console.log(hasName); // true

// Пример 5: Итерация по ключам
Object.keys(person).forEach(key => {
    console.log(`${key}: ${person[key]}`);
});

