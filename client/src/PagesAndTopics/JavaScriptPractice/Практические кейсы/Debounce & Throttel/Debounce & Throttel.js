// ============ Практика debounce и throttle ============

/* 
Debounce (Дебаунс)
Определение: Debounce откладывает выполнение функции до тех пор, пока не пройдет определенное время без новых вызовов.

Принцип работы:
- Каждый новый вызов сбрасывает таймер
- Функция выполняется только после того, как прошло указанное время без новых вызовов
- "Ждет тишины" перед выполнением
*/

/* 
Throttle (Тротлинг)
Определение: Throttle ограничивает частоту выполнения функции, позволяя ей выполняться максимум один раз за определенный интервал времени.

Принцип работы:
- Функция выполняется сразу при первом вызове
- Все последующие вызовы игнорируются до истечения интервала
- После истечения интервала снова разрешается выполнение
*/

/* 
Ключевые различия:
Аспект	Debounce	Throttle
Время выполнения	После паузы в вызовах	С регулярными интервалами
Первый вызов	Откладывается	Выполняется сразу
Последний вызов	Выполняется	Может не выполниться
Частота	Зависит от паузы	Фиксированная
*/

/* 
Практические примеры использования:

Debounce подходит для:
- Поиск в реальном времени (ждем, пока пользователь перестанет печатать)
- Валидация форм (проверяем после того, как пользователь закончил вводить)
- API запросы при вводе (избегаем лишних запросов)

Throttle подходит для:
- Обработка скролла (обновляем позицию с фиксированной частотой)
- Обработка resize событий (пересчитываем размеры не чаще чем нужно)
- Кнопки (предотвращаем множественные клики)
*/


// Реализация debounce
function debounce(func, wait) {
    let timeout;
    return function executedFunction(...args) {
        const later = () => {
            clearTimeout(timeout);
            func(...args);
        };
        clearTimeout(timeout);
        timeout = setTimeout(later, wait);
    };
}

// Реализация throttle
function throttle(func, limit) {
    let inThrottle;
    return function executedFunction(...args) {
        if (!inThrottle) {
            func(...args);
            inThrottle = true;
            setTimeout(() => inThrottle = false, limit);
        }
    };
}