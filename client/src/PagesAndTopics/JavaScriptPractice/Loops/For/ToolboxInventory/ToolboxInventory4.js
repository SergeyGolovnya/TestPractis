// Исходный массив, представляющий ящик с инструментами
// Каждый подмассив - это отдельная коробка с инструментами
// Формат записи: "название_инструмента:цена"
const toolbox = [
    ["молоток:100", "гвозди:10"], // коробка 1
    ["гвозди:20", "шурупы:60"], // коробка 2
    ["отвёртка:80", "пила:30"] // коробка 3
];

// Функция для поиска дорогих инструментов (цена > 50)
function findExpensiveTools(toolbox) {
    // Массив для хранения найденных дорогих инструментов
    const filterTools = [];

    // Внешний цикл: перебор коробок в ящике
    for(let a = 0; a < toolbox.length; a++) {
        // Внутренний цикл: перебор инструментов в каждой коробке
        for (let b = 0; b < toolbox[a].length; b++) {
            // Получаем текущий инструмент в формате "название:цена"
            let tool = toolbox[a][b];
            // Переменная для хранения позиции разделителя ":"
            // Задаем начальное значение -1, если разделитель не найден
            let indexDote = -1;

            // Поиск позиции разделителя ":" в строке инструмента
            for (let s = 0; s < tool.length; s++) {
                // Если символ ":" найден, сохраняем его позицию
                if(tool[s] === ':') {
                    // Сохраняем позицию разделителя
                    indexDote = s;
                    // Прерываем цикл, если разделитель найден
                    break;
                }
            }

            // Если разделитель найден, обрабатываем цену
            if (indexDote !== -1) {
                // Переменная для хранения числового значения цены
                let price = 0;
                // Преобразование строки цены в число
                for (let priceNum = indexDote + 1; priceNum < tool.length; priceNum++) {
                    // Преобразование символа в цифру
                    // charCodeAt - возвращает числовое значение символа
                    let digit = tool[priceNum].charCodeAt(0) - '0'.charCodeAt(0);
                    // Формирование числа из цифр
                    // Умножаем текущее значение price на 10 и прибавляем текущую цифру в итогде получается число пример 100
                    price = price * 10 + digit;
                }

                // Проверка, является ли инструмент дорогим (цена > 50)
                if (price > 50) {
                    // Извлечение названия инструмента (все символы до ":")
                    let name = '';
                    for (let s = 0; s < indexDote; s++) {
                        name += tool[s];
                    }
                    // Добавление названия в массив дорогих инструментов
                    filterTools.push(name);
                }
            }
        }
    }

    // Возврат массива с названиями дорогих инструментов
    return filterTools;
}

// Тестовые вызовы функции
console.log(findExpensiveTools([["молоток:100", "гвозди:10"], ["гвозди:20", "шурупы:60"], ["отвёртка:80", "пила:30"]])); // ["молоток", "шурупы", "отвёртка"]
console.log(findExpensiveTools([["пила:40"]])); // []
console.log(findExpensiveTools([])); // []