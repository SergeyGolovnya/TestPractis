// Создаем массив toolbox с разными уровнями вложенности
const toolbox = [
    "молоток","пила1", // на верхнем уровне
    ["гвозди", "шурупы","пила2"], // 1 уровень вложенности
    [["отвёртка","пила3"]], // 2 уровня
    [[["пила4"], "гвозди"]] // 3 уровня
  ];

// Функция для поиска всех элементов, содержащих слово "пила"
function findAllPiles(toolbox) {
    // Создаем массив для хранения найденных пил
    const piles = [];
    // Создаем очередь и добавляем в неё начальный массив
    const queue = [...toolbox]; // Распаковываем массив сразу

    // Пока в очереди есть элементы
    while (queue.length > 0) {
        // Берем первый элемент из очереди
        const current = queue.shift();
        
        // Если текущий элемент - строка и содержит слово "пила"
        if (typeof current === 'string' && current.includes('пила')) {
            // Добавляем в результат
            piles.push(current);
        }
        // Если текущий элемент - массив
        else if (Array.isArray(current)) {
            // Добавляем все элементы массива в начало очереди
            queue.unshift(...current);
        }
    }

    // Возвращаем массив с найденными пилами
    return piles;
}

// Выводим результат работы функции в консоль
console.log(findAllPiles(toolbox)); // → ["пила1", "пила2", "пила3", "пила4"]
