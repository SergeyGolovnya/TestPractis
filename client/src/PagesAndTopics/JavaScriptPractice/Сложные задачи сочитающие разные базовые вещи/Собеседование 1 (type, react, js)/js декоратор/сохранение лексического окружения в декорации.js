// 1. Что происходит в строке `const onceLol = once(() => console.log("Lol"))`

// Шаг 1: Создание функции-аргумента

() => console.log("Lol")

// Это **стрелочная функция** (arrow function). Она просто выводит "Lol" в консоль.

// Шаг 2: Передача функции в `once()`

once(() => console.log("Lol"))

// Мы передаем нашу стрелочную функцию как аргумент в функцию `once`.

// Шаг 3: Что возвращает `once()` Посмотрим на код функции `once`:

function once(fn) {
    let called = false
    let result
    
    return function (...args) {  // ← ВОТ ЭТО ВАЖНО!
        if (!called) {
            called = true
            result = fn.apply(this, args)
            return result
        }
        return result
    }
}


// Функция `once` **возвращает новую функцию**! Эта новая функция "запоминает" переданную функцию `fn` и переменные `called` и `result`.

// 2. Что такое `onceLol` после присваивания

const onceLol = once(() => console.log("Lol"))

// После этого `onceLol` - это **функция**, которая была возвращена из `once()`. То есть:

// onceLol теперь это функция, которая выглядит примерно так:
onceLol = function (...args) {
    if (!called) {
        called = true
        result = fn.apply(this, args)  // fn = () => console.log("Lol")
        return result
    }
    return result
}

// 3. Почему можно вызывать `onceLol()`

// Поскольку `onceLol` теперь является функцией, вы можете вызывать её как любую другую функцию:

// onceLol(); // Вызывает функцию, которая была возвращена из once()

// 4. Аналогия с вашим примером

// Да, вы абсолютно правы! Это точно такая же механика:

// const onceLol = () => {}  // Создаем функцию
// onceLol()                 // Вызываем функцию

// Разница только в том, что в нашем случае функция создается не напрямую, а возвращается из другой функции.

// 5. Замыкание (Closure)

// Ключевой момент - **замыкание**. Функция, возвращенная из `once()`, "запоминает" переменные `called`, `result` и функцию `fn` из области видимости `once()`.

function once(fn) {
    let called = false  // ← Эта переменная "запоминается"
    let result         // ← И эта тоже
    
    return function (...args) {
        // Эта функция имеет доступ к called, result и fn
        if (!called) {
            called = true
            result = fn.apply(this, args)
            return result
        }
        return result
    }
}

// 6. Практический пример

// Создаем функцию, которая будет вызвана только один раз
const onceLol = once(() => console.log("Lol"))

// Первый вызов - выполняется оригинальная функция
onceLol(); // Выводит: "Lol"

// Второй вызов - возвращается сохраненный результат, функция не выполняется
onceLol(); // Ничего не выводит

// Резюме:
// 1. `once()` принимает функцию как аргумент
// 2. `once()` возвращает **новую функцию**
// 3. Эта новая функция "запоминает" оригинальную функцию и состояние
// 4. Мы сохраняем эту новую функцию в переменную `onceLol`
// 5. Теперь `onceLol` - это функция, которую можно вызывать
// 6. При вызове `onceLol()` выполняется логика из `once()` с "запомненной" оригинальной функцией